@router.get("/analytics")
async def get_analytics(authorization: Optional[str] = Header(None)):
    sb = get_supabase()
    user_id = _get_user_id(authorization)
        
    res = sb.table("resumes").select("id, uploaded_at, resume_analyses(overall_score, ats_score, content_score, skills_score, formatting_score, grammar_score)").eq("user_id", user_id).order("uploaded_at", desc=False).execute()
    
    trend = []
    radar = [
        {"subject": "Content", "A": 0, "count": 0},
        {"subject": "Skills", "A": 0, "count": 0},
        {"subject": "Formatting", "A": 0, "count": 0},
        {"subject": "Grammar", "A": 0, "count": 0},
    ]
    
    for r in res.data:
        analyses = r.get("resume_analyses", [])
        if not analyses:
            continue
            
        a = analyses[0] # latest analysis for this resume
        date_str = r.get("uploaded_at", "").split("T")[0]
        
        trend.append({
            "date": date_str[-5:], # 09-01
            "score": a.get("overall_score", 0) or 0,
            "ats": a.get("ats_score", 0) or 0
        })
        
        radar[0]["A"] += a.get("content_score", 0) or 0
        radar[0]["count"] += 1
        radar[1]["A"] += a.get("skills_score", 0) or 0
        radar[1]["count"] += 1
        radar[2]["A"] += a.get("formatting_score", 0) or 0
        radar[2]["count"] += 1
        radar[3]["A"] += a.get("grammar_score", 0) or 0
        radar[3]["count"] += 1
        
    for item in radar:
        if item["count"] > 0:
            item["A"] = round(item["A"] / item["count"])
        else:
            item["A"] = 0
            
    return {"trend": trend, "radar": radar}


@router.delete("/{resume_id}")
async def delete_resume(resume_id: str, authorization: Optional[str] = Header(None)):
    user_id = _get_user_id(authorization)
    sb = get_supabase()

    resume = sb.table("resumes").select("id").eq("id", resume_id).eq("user_id", user_id).execute()
    if not resume.data:
        raise HTTPException(status_code=404, detail="Resume not found.")

    sb.table("skills").delete().eq("resume_id", resume_id).execute()
    sb.table("resume_analyses").delete().eq("resume_id", resume_id).execute()
    sb.table("resumes").delete().eq("id", resume_id).execute()

    return {"message": "Resume deleted successfully."}


